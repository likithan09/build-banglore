# Now update frontend/src/i18n/translations.ts
translations_ts = os.path.join("frontend", "src", "i18n", "translations.ts")
with open(translations_ts, "r", encoding="utf-8") as f:
    ts_code = f.read()

# Read all updated locales
all_translations = {}
for lang in PAYMENT_KEYS.keys():
    json_path = os.path.join(locales_dir, f"{lang}.json")
    if os.path.exists(json_path):
        with open(json_path, "r", encoding="utf-8") as f:
            all_translations[lang] = json.load(f)

# Re-serialize TRANSLATIONS in translations.ts
# Find where export const TRANSLATIONS begins
prefix_match = re.search(r'export const TRANSLATIONS: Record<string, Record<string, string>> = \{', ts_code)
if prefix_match:
    start_pos = prefix_match.start()
    header_part = ts_code[:start_pos]
    
    # Build clean ts output
    new_ts = header_part + "export const TRANSLATIONS: Record<string, Record<string, string>> = " + json.dumps(all_translations, ensure_ascii=False, indent=2) + ";\n"
    with open(translations_ts, "w", encoding="utf-8") as f:
        f.write(new_ts)
    print("Successfully updated frontend/src/i18n/translations.ts")
